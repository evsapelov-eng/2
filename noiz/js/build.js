#!/usr/bin/env node
// Concatenates the ES5 core + Max adapter into max/noiz_engine.js and copies the
// jsui file into max/. One self-contained file per Max object: no require(),
// no search-path surprises after Freeze.
"use strict";
const fs = require("fs");
const path = require("path");
const { sourceFiles } = require("./node_loader");

const ROOT = path.join(__dirname, "..");
const OUT = path.join(ROOT, "max");

function es5Check(file, text) {
  const banned = [/\blet\s/, /\bconst\s/, /=>/, /\bclass\s/, /`/, /Math\.imul/, /\.\.\.[a-zA-Z_]/, /Math\.random/];
  const bad = banned.filter((re) => re.test(text.replace(/\/\/.*$/gm, "")));
  if (bad.length) throw new Error(`${file}: non-ES5/forbidden construct ${bad.join(", ")}`);
}

const parts = [];
for (const f of sourceFiles().concat([path.join(__dirname, "max_adapter.js")])) {
  const t = fs.readFileSync(f, "utf8");
  es5Check(path.basename(f), t);
  parts.push(`// ---- ${path.relative(ROOT, f)} ----\n${t}`);
}
// Legacy Max JS may read files with a non-UTF-8 codepage: escape everything non-ASCII.
const ascii = (t) => t.replace(/[^\x00-\x7f]/g, (c) => "\\u" + c.charCodeAt(0).toString(16).padStart(4, "0"));
const header = "// GENERATED by js/build.js — do not edit. Sources: noiz/js/src + noiz/js/max_adapter.js\n";
fs.writeFileSync(path.join(OUT, "noiz_engine.js"), ascii(header + parts.join("\n")));

const uiSrc = path.join(__dirname, "ui", "noiz_ui.js");
if (fs.existsSync(uiSrc)) {
  const t = fs.readFileSync(uiSrc, "utf8");
  es5Check("noiz_ui.js", t);
  fs.writeFileSync(path.join(OUT, "noiz_ui.js"), ascii(header + t));
}
console.log("built max/noiz_engine.js" + (fs.existsSync(uiSrc) ? " and max/noiz_ui.js" : ""));
