#!/usr/bin/env python3
"""Writes gen/stomp.genexpr (helpers + Params + Histories + modulation block + gen/voice.part.genexpr)
and the SPEC block of js/stomp_ui.js from tools/spec.py.  --check: fail if either file is stale."""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from spec import KNOBS, NAMES, SOURCES, DEPTH_DEFAULTS, depth_names  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GEN = os.path.join(ROOT, "gen", "stomp.genexpr")
PART = os.path.join(ROOT, "gen", "voice.part.genexpr")
UI = os.path.join(ROOT, "js", "stomp_ui.js")

HEAD = """// STØMP — kick drum voice for a [gen~] codebox. GENERATED by tools/make_engine.py from tools/spec.py
// and gen/voice.part.genexpr — edit those, then `npm run gen`.
// Rules (from FLØCK's real-Max lessons): functions first, then Param/Data/History; History written
// only at the top level at the end of the pass; no loops.
// Messages: ktrig <n> (a new value = a new hit), knote <0..127>, kvel <0..1>, plus every knob.
// in1: unused (instrument).  out1/out2: L/R.  out3: amp envelope (panel).
sknee(x) { ax = abs(x); return ax < 0.9 ? x : (x < 0 ? -1 : 1) * (0.9 + 0.1 * tanh((ax - 0.9) / 0.1)); }
pw2(x) { return exp(x * 0.69314718); }
shapep(v) { return pw2((0.5 - v) * 6); }
wrapi(i, n) { return i < 0 ? i + n : (i >= n ? i - n : i); }
"""

VOICE_HIST = ["act", "tt", "ph", "pm", "p2", "p3", "p4", "p5", "nlL", "nlR", "nhL", "nhR", "dcL", "dcR",
              "yL", "yR", "slL", "slR", "rl1", "rl2", "rl3", "rl4", "rwi"]


def engine():
    o = [HEAD]
    o.append("Param ktrig(0);")
    o.append("Param knote(36, min=0, max=127);")
    o.append("Param kvel(1, min=0, max=1);")
    for n, _s, _l, _ln, d in KNOBS:
        o.append("Param %s(%g, min=0, max=1);" % (n, d))
    for n, _l, _ln, d in SOURCES:
        o.append("Param %s(%g, min=0, max=1);" % (n, d))
    for n in depth_names():
        o.append("Param %s(%g, min=-1, max=1);" % (n, DEPTH_DEFAULTS.get(n, 0)))
    o.append("Data room(8192, 4);")
    o.append("History init(0);")
    o.append("History lastk(0);")
    for n, _s, _l, _ln, d in KNOBS:
        o.append("History s_%s(%g);" % (n, d))
        o.append("History o_%s(0);" % n)
    for h in VOICE_HIST:
        o.append("History %s(0);" % h)
    o.append("")
    o.append("// ===== per-hit modulation (generated): knob smoothed per sample + offset latched at the hit =====")
    o.append("// velocity source: 0 at full velocity .. −1 at the softest; random: −0.5 .. 0.5, new for every hit")
    o.append("trig = init > 0.5 && ktrig != lastk;")
    o.append("vsrc = kvel - 1;")
    o.append("sk = init > 0.5 ? 0.002 : 1;")
    for n, *_ in KNOBS:
        o.append("n_%s = s_%s + (%s - s_%s) * sk;" % (n, n, n, n))
        o.append("q_%s = trig ? (v_%s * vel_amt * vsrc + r_%s * rnd_amt * noise() * 0.5) : o_%s;" % (n, n, n, n))
        o.append("e_%s = clamp(n_%s + q_%s, 0, 1);" % (n, n, n))
    o.append("")
    o.append(open(PART, encoding="utf-8").read().rstrip())
    o.append("init = 1;")
    o.append("lastk = ktrig;")
    for n, *_ in KNOBS:
        o.append("s_%s = n_%s;" % (n, n))
        o.append("o_%s = q_%s;" % (n, n))
    return "\n".join(o) + "\n"


def ui_spec():
    knobs = [{"n": n, "sec": s, "lab": l, "d": d} for n, s, l, _ln, d in KNOBS]
    src = [{"n": n, "lab": l, "d": d} for n, l, _ln, d in SOURCES]
    deps = {n: DEPTH_DEFAULTS.get(n, 0) for n in depth_names()}
    return ("// <SPEC> generated by tools/make_engine.py from tools/spec.py — do not edit by hand\n"
            "var SPEC_KNOBS = " + json.dumps(knobs) + ";\n"
            "var SPEC_SOURCES = " + json.dumps(src) + ";\n"
            "var SPEC_DEPTHS = " + json.dumps(deps) + ";\n"
            "// </SPEC>")


def main():
    check = "--check" in sys.argv
    stale = []
    want = engine()
    if not os.path.exists(GEN) or open(GEN, encoding="utf-8").read() != want:
        stale.append(GEN)
        if not check:
            open(GEN, "w", encoding="utf-8").write(want)
    ui = open(UI, encoding="utf-8").read()
    new = re.sub(r"// <SPEC>.*?// </SPEC>", lambda m: ui_spec(), ui, flags=re.S)
    if new != ui:
        stale.append(UI)
        if not check:
            open(UI, "w", encoding="utf-8").write(new)
    if check and stale:
        print("stale (run npm run gen):", ", ".join(os.path.relpath(s, ROOT) for s in stale))
        sys.exit(1)
    print("engine:", os.path.relpath(GEN, ROOT), "OK" if not stale else "written")


if __name__ == "__main__":
    main()
