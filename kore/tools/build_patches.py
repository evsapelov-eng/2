#!/usr/bin/env python3
"""Generates the KØRE Max patch SOURCES (.maxpat) from spec/dsp_map.json.

STATIC VALID at best (see tools/validate_maxpat.py, tests/patch_sim.test.js). Max/Live
host checks are NOT done by this script. Objects relied on: docs/MAX_API_TO_VERIFY.md.

Envelopes: [line~] in dB → [dbtoa~]  (linear dB ramp = exponential amplitude).
Pitch sweep (spec §03): f = f0 * 2^((semis/12) * e(t)),  e = dbtoa(dB ramp 0 → -60 over sweepMs)
  realised as  line~ → dbtoa~ → *~ (semis/12 * 6.0206) → dbtoa~ → *~ f0 → cycle~
  (2^x = dbtoa(6.0206 x)).
Voice input list (8 values): amp p0 p1 p2 p3 p4 open pan — p* = KORE_VOICE_PARAMS without pan.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _patcher_base import Patcher, fmt  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAP = json.load(open(os.path.join(ROOT, "spec", "dsp_map.json")))
OUT = os.path.join(ROOT, "max")
E = MAP["envelope"]
LN2_DB = 6.0206  # 20*log10(2)


def f(v):
    return fmt(float(v))


def expmap(r):
    lo, hi = float(r[0]), float(r[1])
    return "expr %s*pow(%s/%s\\,$f1)" % (f(lo), f(hi), f(lo))


def voice_head(P, name):
    """in 1 → [t l b l]: right list first (params), then bang (phase/click reset), then left list (envelopes)."""
    P.comment("KØRE voice %s — poly~ instance. GENERATED by tools/build_patches.py from spec/dsp_map.json. "
              "Input: amp p0 p1 p2 p3 p4 open pan." % name, 20, 8, 900)
    inp = P.obj("in 1", 20, 40)
    trig = P.obj("t l b l", 20, 70, 80)
    P.connect(inp, 0, trig, 0)
    params = P.obj("unpack 0. 0. 0. 0. 0. 0. 0. 0.", 400, 110, 280)
    env = P.obj("unpack 0. 0. 0. 0. 0. 0. 0. 0.", 20, 110, 280)
    P.connect(trig, 2, params, 0)
    P.connect(trig, 0, env, 0)
    return trig, params, env


def amp_env(P, x, y, decay_ms_box, attack_ms=None):
    """Exponential amp envelope + gate (frees thispoly~). Returns (env_signal, gate_signal)."""
    a = attack_ms if attack_ms is not None else E["attackMs"]
    t = P.obj("t f f", x, y, 50)
    P.connect(decay_ms_box, 0, t, 0)
    m_env = P.msg("%s, 0 %s %s $1" % (int(E["floorDb"]), f(a), int(E["floorDb"])), x, y + 30)
    tot = P.obj("expr $f1+%s" % f(a), x + 160, y + 30, 90)
    m_gate = P.msg("1, 1 $1 0 %s" % f(E["gateFadeMs"]), x + 160, y + 60)
    P.connect(t, 1, m_env, 0)
    P.connect(t, 0, tot, 0)
    P.connect(tot, 0, m_gate, 0)
    le = P.obj("line~", x, y + 90, 50)
    lg = P.obj("line~", x + 160, y + 90, 50)
    P.connect(m_env, 0, le, 0)
    P.connect(m_gate, 0, lg, 0)
    db = P.obj("dbtoa~", x, y + 120)
    P.connect(le, 0, db, 0)
    ge = P.obj("*~", x, y + 150, 40)
    P.connect(db, 0, ge, 0)
    P.connect(lg, 0, ge, 1)
    busy = P.obj("thispoly~", x + 160, y + 150)
    P.connect(lg, 0, busy, 0)
    P._gate = lg   # gate signal (1 → 0 at the end of the note), reused by extra layers
    return ge


TAU60 = 6.907755  # exp(-t/tau) reaches -60 dB after 6.9078*tau


def sweep_osc(P, x, y, trig_bang, f0_box, depth_box_or_semis, sweep_ms_box_or_const):
    """Phase-reset sine whose frequency glides f0*2^(semis/12*e(t)), e = exp(-t/tau).
    The dB ramp runs 0 → -60 dB over 6.9078*tau (box values are already in that unit)."""
    if isinstance(sweep_ms_box_or_const, (int, float)):
        t60 = sweep_ms_box_or_const * TAU60
        m_s = P.msg("0, -60 %s -120 %s" % (f(t60), f(t60)), x, y)
        P.connect(trig_bang, 0, m_s, 0)
    else:
        m_s = P.msg("0, -60 $1 -120 $1", x, y)
        P.connect(sweep_ms_box_or_const, 0, m_s, 0)
    ls = P.obj("line~", x, y + 30, 50)
    P.connect(m_s, 0, ls, 0)
    d1 = P.obj("dbtoa~", x, y + 60)
    P.connect(ls, 0, d1, 0)
    if isinstance(depth_box_or_semis, (int, float)):
        dm = P.obj("*~ %s" % f(depth_box_or_semis / 12.0 * LN2_DB), x, y + 90)
        P.connect(d1, 0, dm, 0)
    else:
        dm = P.obj("*~ 0.", x, y + 90)
        P.connect(d1, 0, dm, 0)
        P.connect(depth_box_or_semis, 0, dm, 1)
    d2 = P.obj("dbtoa~", x, y + 120)
    P.connect(dm, 0, d2, 0)
    fm = P.obj("*~ 50.", x, y + 150)
    P.connect(d2, 0, fm, 0)
    P.connect(f0_box, 0, fm, 1)
    osc = P.obj("cycle~", x, y + 180, 50)
    P.connect(fm, 0, osc, 0)
    ph = P.msg("0.75", x + 80, y + 150)
    P.connect(trig_bang, 0, ph, 0)
    # phase reset on every note: cycle~ is a cosine, phase 0.75 makes it start at 0 like
    # sin() in the model → deterministic onset without a step (spec §03 onset policy)
    P.connect(ph, 0, osc, 1)
    return osc


def finish(P, sig, amp_box, x, y, drive_boxes=None, out_gain=1.0, pan_box=None):
    """[drive] → amp → out~ 1  (with pan_box: balance → out~ 1 / out~ 2)."""
    s = sig
    og = P.obj("*~ %s" % f(out_gain), x, y)
    P.connect(s, 0, og, 0)
    s = og
    if drive_boxes:
        pre = P.obj("*~ 1.", x, y + 30)
        th = P.obj("tanh~", x, y + 60)
        comp = P.obj("*~ 1.", x, y + 90)
        P.chain(s, pre, th, comp)
        P.connect(drive_boxes[0], 0, pre, 1)
        P.connect(drive_boxes[1], 0, comp, 1)
        s = comp
        y += 90
    va = P.obj("*~ 0.", x, y + 30)
    P.connect(s, 0, va, 0)
    P.connect(amp_box, 0, va, 1)
    if pan_box is None:
        o = P.obj("out~ 1", x, y + 60)
        P.connect(va, 0, o, 0)
        return
    # balance law (centre = mono level on both sides); set before the note starts
    for ch, ex in ((1, "expr min(1.\\,2.*(1.-$f1))"), (2, "expr min(1.\\,2.*$f1)")):
        cx = x + (ch - 1) * 140
        g = P.obj(ex, cx, y + 60, 130)
        P.connect(pan_box, 7, g, 0)
        gm = P.msg("$1", cx, y + 90)   # jump: a ramp would soften the attack of every hit
        P.connect(g, 0, gm, 0)
        gl = P.obj("line~", cx, y + 120, 50)
        P.connect(gm, 0, gl, 0)
        m = P.obj("*~", cx, y + 150, 40)
        P.connect(va, 0, m, 0); P.connect(gl, 0, m, 1)
        o = P.obj("out~ %d" % ch, cx, y + 180)
        P.connect(m, 0, o, 0)


def lin_expr(r):
    return "expr %s+%s*$f1" % (f(r[0]), f(r[1] - r[0]))


def depth_expr(r):
    """sweep semis range → *~ factor for the 2^x = dbtoa(6.0206 x) trick."""
    return "expr (%s+%s*$f1)/12.*%s" % (f(r[0]), f(r[1] - r[0]), f(LN2_DB))


def build_sub():
    v = MAP["voices"]["SUB"]
    P = Patcher((40, 40, 1300, 900))
    trig, prm, env = voice_head(P, "SUB")   # params: tune decay sweep drive
    f0 = P.obj(expmap(v["tuneHz"]), 400, 150, 200)
    P.connect(prm, 1, f0, 0)
    depth = P.obj(depth_expr(v["sweepSemisRange"]), 620, 150, 220)
    P.connect(prm, 3, depth, 0)
    drv_t = P.obj("t f f", 860, 150, 50)
    P.connect(prm, 4, drv_t, 0)
    pre = P.obj(lin_expr(v["driveGain"]), 860, 180, 120)
    comp = P.obj("expr pow(%s+%s*$f1\\,-0.3)" % (f(v["driveGain"][0]), f(v["driveGain"][1] - v["driveGain"][0])), 990, 180, 170)
    P.connect(drv_t, 1, pre, 0); P.connect(drv_t, 0, comp, 0)
    dec = P.obj(expmap(v["decayMs"]), 220, 300, 180)
    P.connect(env, 2, dec, 0)
    osc = sweep_osc(P, 420, 300, trig_bang=trig_b(P, trig), f0_box=f0, depth_box_or_semis=depth, sweep_ms_box_or_const=float(v["sweepMs"]))
    ge = amp_env(P, 20, 400, dec)
    body = P.obj("*~", 420, 520, 40)
    P.connect(osc, 0, body, 0); P.connect(ge, 0, body, 1)
    finish(P, body, prm, 420, 560, drive_boxes=(pre, comp), out_gain=v["outGain"])
    return P.dump(os.path.join(OUT, "kore_voice_sub.maxpat"))


def trig_b(P, trig):
    """A [t b] on outlet 1 of [t l b l] (the bang between params and envelopes), one per patch."""
    if getattr(P, "_trig_bang", None) is None:
        P._trig_bang = P.obj("t b", 120, 70, 40)
        P.connect(trig, 1, P._trig_bang, 0)
    return P._trig_bang


def build_tom(name):
    """Kick-like tom: glide body + CLICK (band-passed noise + tick at clickHz) → tanh DRIVE → pan."""
    v = MAP["voices"][name]
    P = Patcher((40, 40, 1300, 1000))
    trig, prm, env = voice_head(P, name)   # params: tune decay sweep drive snap ; [7] = pan
    f0 = P.obj(expmap(v["tuneHz"]), 400, 150, 200)
    P.connect(prm, 1, f0, 0)
    depth = P.obj(depth_expr(v["sweepSemisRange"]), 620, 150, 220)
    P.connect(prm, 3, depth, 0)
    drv_t = P.obj("t f f", 860, 150, 50)
    P.connect(prm, 4, drv_t, 0)
    g0, g1 = v["driveGain"]
    pre = P.obj("expr %s*pow(%s/%s\\,$f1)*%s" % (f(g0), f(g1), f(g0), f(v["outGain"])), 860, 180, 200)
    comp = P.obj("expr pow(%s*pow(%s/%s\\,$f1)\\,-0.3)" % (f(g0), f(g1), f(g0)), 1070, 180, 200)
    P.connect(drv_t, 1, pre, 0); P.connect(drv_t, 0, comp, 0)
    snapg = P.obj("expr $f1*%s" % f(v["clickGain"]), 980, 120, 110)
    P.connect(prm, 5, snapg, 0)
    dec = P.obj(expmap(v["decayMs"]), 220, 300, 180)
    P.connect(env, 2, dec, 0)
    tb = trig_b(P, trig)
    osc = sweep_osc(P, 420, 300, trig_bang=tb, f0_box=f0, depth_box_or_semis=depth, sweep_ms_box_or_const=float(v["sweepMs"]))
    ge = amp_env(P, 20, 400, dec)
    body = P.obj("*~", 420, 520, 40)
    P.connect(osc, 0, body, 0); P.connect(ge, 0, body, 1)
    # CLICK: noise band at clickHz (x2.2, tau clickTauMs) + tick sine at clickHz (tau tickTauMs)
    nz = P.obj("noise~", 700, 300)
    bp = P.obj("svf~ %s %s" % (f(v["clickHz"]), f(v["clickQ"])), 700, 330)
    P.connect(nz, 0, bp, 0)
    nb = P.obj("*~ 2.2", 700, 360)
    P.connect(bp, 2, nb, 0)
    def burst(xx, tau):
        t60 = tau * TAU60
        m_ = P.msg("0, -60 %s -120 %s" % (f(t60), f(t60)), xx, 300)
        P.connect(tb, 0, m_, 0)
        l_ = P.obj("line~", xx, 330, 50)
        P.connect(m_, 0, l_, 0)
        d_ = P.obj("dbtoa~", xx, 360)
        P.connect(l_, 0, d_, 0)
        return d_
    ce = burst(860, v["clickTauMs"])
    c1 = P.obj("*~", 700, 400, 40)
    P.connect(nb, 0, c1, 0); P.connect(ce, 0, c1, 1)
    tk = P.obj("cycle~ %s" % f(v["clickHz"]), 1000, 360)
    tph = P.msg("0.75", 1080, 330)
    P.connect(tb, 0, tph, 0); P.connect(tph, 0, tk, 1)
    te = burst(1000, v["tickTauMs"])
    c2 = P.obj("*~", 1000, 400, 40)
    P.connect(tk, 0, c2, 0); P.connect(te, 0, c2, 1)
    cs = P.obj("+~", 860, 440, 40)
    P.connect(c1, 0, cs, 0); P.connect(c2, 0, cs, 1)
    c3 = P.obj("*~ 0.", 860, 470)
    P.connect(cs, 0, c3, 0); P.connect(snapg, 0, c3, 1)
    c4 = P.obj("*~", 860, 500, 40)
    P.connect(c3, 0, c4, 0); P.connect(P._gate, 0, c4, 1)   # click ends with the note
    tot = P.obj("+~", 420, 560, 40)
    P.connect(body, 0, tot, 0); P.connect(c4, 0, tot, 1)
    finish(P, tot, prm, 420, 600, drive_boxes=(pre, comp), out_gain=1.0, pan_box=prm)
    return P.dump(os.path.join(OUT, "kore_voice_%s.maxpat" % name.lower().replace(" ", "")))


def build_hat():
    v = MAP["voices"]["HAT"]
    P = Patcher((40, 40, 1100, 800))
    trig, prm, env = voice_head(P, "HAT")   # params: tone decay reso open ; list[6] = open articulation
    th = P.obj(expmap(v["toneHz"]), 400, 150, 200)
    P.connect(prm, 1, th, 0)
    q = P.obj(lin_expr(v["q"]), 620, 150, 120)
    P.connect(prm, 3, q, 0)
    # closed: decay ; open: decay * openFactor(OPEN)   ($f2 = articulation, $f3 = OPEN; both arrive first)
    lo, hi = v["decayMs"]
    o0, o1 = v["openFactor"]
    dec = P.obj("expr %s*pow(%s/%s\\,$f1)*(1.+(%s+%s*$f3-1.)*$f2)" % (f(lo), f(hi), f(lo), f(o0), f(o1 - o0)), 20, 300, 360)
    P.connect(env, 6, dec, 1)
    P.connect(env, 4, dec, 2)
    P.connect(env, 2, dec, 0)
    nz = P.obj("noise~", 420, 300)
    hp = P.obj("svf~ 8000. 0.3", 420, 330)
    P.connect(nz, 0, hp, 0); P.connect(th, 0, hp, 1); P.connect(q, 0, hp, 2)
    ge = amp_env(P, 20, 400, dec, attack_ms=0.3)
    body = P.obj("*~", 420, 600, 40)
    P.connect(hp, 1, body, 0); P.connect(ge, 0, body, 1)
    finish(P, body, prm, 420, 640, out_gain=v["outGain"], pan_box=prm)
    return P.dump(os.path.join(OUT, "kore_voice_hat.maxpat"))


def build_rumble():
    v = MAP["voices"]["RUMBLE"]
    P = Patcher((40, 40, 1100, 800))
    P.comment("KØRE RUMBLE bus (not per hit). In 1: kick audio · In 2: RUMBLE step 'amp amount tail duck tone drive open' · "
              "In 3: kick proximity signal (1 at a kick → 0 after the release) for the duck. Feedback bounded (fbMax).", 20, 8, 1000)
    i_sig = P.raw({"maxclass": "inlet", "numinlets": 0, "numoutlets": 1, "outlettype": ["signal"], "patching_rect": [20, 40, 30, 30], "comment": "kick audio"})
    i_msg = P.raw({"maxclass": "inlet", "numinlets": 0, "numoutlets": 1, "outlettype": [""], "patching_rect": [400, 40, 30, 30], "comment": "RUMBLE step"})
    i_prox = P.raw({"maxclass": "inlet", "numinlets": 0, "numoutlets": 1, "outlettype": ["signal"], "patching_rect": [760, 40, 30, 30], "comment": "kick proximity"})
    lp = P.obj("svf~ 220. %s" % f(v["lowpassQ"]), 20, 90)
    P.connect(i_sig, 0, lp, 0)
    fbsum = P.obj("+~", 20, 130, 40)
    P.connect(lp, 0, fbsum, 0)
    tin = P.obj("tapin~ 1200", 20, 170)
    P.connect(fbsum, 0, tin, 0)
    tout = P.obj("tapout~ %s %s" % (f(v["tapsMs"][0]), f(v["tapsMs"][1])), 20, 210, 140)
    P.connect(tin, 0, tout, 0)
    ts = P.obj("+~", 20, 250, 40)
    P.connect(tout, 0, ts, 0); P.connect(tout, 1, ts, 1)
    half = P.obj("*~ 0.5", 20, 280)
    P.connect(ts, 0, half, 0)
    fb = P.obj("*~ 0.", 180, 280)
    P.connect(half, 0, fb, 0)
    P.connect(fb, 0, fbsum, 1)
    up = P.obj("unpack 0. 0. 0. 0. 0. 0. 0.", 400, 90, 260)
    P.connect(i_msg, 0, up, 0)
    avg = (v["tapsMs"][0] + v["tapsMs"][1]) / 2.0
    tail = P.obj(expmap(v["tailMs"]), 400, 130, 200)
    P.connect(up, 2, tail, 0)
    tt = P.obj("t f f", 400, 160, 50)
    P.connect(tail, 0, tt, 0)
    fbx = P.obj("expr min(%s\\,pow(10.\\,-3.*%s/$f1))" % (f(v["fbMax"]), f(avg)), 400, 190, 230)
    P.connect(tt, 0, fbx, 0)
    P.connect(fbx, 0, fb, 1)
    gm = P.msg("1 %s 1 $1 0 $1" % f(v["gateAttackMs"]), 560, 220)
    P.connect(tt, 1, gm, 0)
    gl = P.obj("line~", 560, 250, 50)
    P.connect(gm, 0, gl, 0)
    am = P.msg("$1 10", 400, 250)
    P.connect(up, 1, am, 0)
    al = P.obj("line~", 400, 280, 50)
    P.connect(am, 0, al, 0)
    lpf = P.obj(expmap(v["lowpassHz"]), 640, 130, 200)
    P.connect(up, 4, lpf, 0)
    P.connect(lpf, 0, lp, 1)
    drv_t = P.obj("t f f", 860, 130, 50)
    P.connect(up, 5, drv_t, 0)
    pre = P.obj(expmap(v["driveGain"]), 860, 160, 180)
    comp = P.obj("expr pow(%s*pow(%s/%s\\,$f1)\\,-0.3)" % (f(v["driveGain"][0]), f(v["driveGain"][1]), f(v["driveGain"][0])), 860, 190, 230)
    P.connect(drv_t, 1, pre, 0); P.connect(drv_t, 0, comp, 0)
    dpre = P.obj("*~ 1.", 20, 320)
    dth = P.obj("tanh~", 20, 350)
    dcomp = P.obj("*~ 1.", 20, 380)
    P.connect(half, 0, dpre, 0); P.chain(dpre, dth, dcomp)
    P.connect(pre, 0, dpre, 1); P.connect(comp, 0, dcomp, 1)
    # duck from the kick proximity: g = 1 - duck * prox
    dk = P.obj("*~ %s" % f(v["defaults"]["duck"]), 760, 250)
    P.connect(i_prox, 0, dk, 0)
    P.connect(up, 3, dk, 1)
    dg = P.obj("!-~ 1.", 760, 280)
    P.connect(dk, 0, dg, 0)
    g1 = P.obj("*~", 20, 420, 40)
    P.connect(dcomp, 0, g1, 0); P.connect(gl, 0, g1, 1)
    g2 = P.obj("*~", 20, 450, 40)
    P.connect(g1, 0, g2, 0); P.connect(dg, 0, g2, 1)
    g3 = P.obj("*~", 20, 480, 40)
    P.connect(g2, 0, g3, 0); P.connect(al, 0, g3, 1)
    wet = P.obj("*~ %s" % f(v["wetGain"]), 20, 510)
    P.connect(g3, 0, wet, 0)
    o = P.raw({"maxclass": "outlet", "numinlets": 1, "numoutlets": 0, "patching_rect": [20, 550, 30, 30], "comment": "RUMBLE out"})
    P.connect(wet, 0, o, 0)
    return P.dump(os.path.join(OUT, "kore_rumble.maxpat"))


def build_kick():
    """Sample-accurate kick: transport-locked bar phase → 16 steps → on a step with a hit
    (pattern buffer) hold step+amp (sah~); time since the hit (samples) indexes the
    rendered kick buffer. Out 1: kick audio. Out 2: kick proximity (1 at the hit → 0
    after the duck release) for the low-end coordinator."""
    P = Patcher((40, 40, 1200, 900))
    P.comment("KØRE kick player (signal domain, sample-accurate). Messages: set <buffer>, level <amp>, tempo <bpm>, "
              "sr <rate>, playing <0|1>. Buffers ---kick_a/---kick_b (sound) and ---kpat (16-step pattern) are written by kore_engine.js.", 20, 8, 1100)
    P.obj("buffer~ ---kick_a 2000", 900, 40, 200)
    P.obj("buffer~ ---kick_b 2000", 900, 70, 200)
    P.obj("buffer~ ---kpat 1", 900, 100, 200)
    P.obj("buffer~ ---kgap 1", 900, 130, 200)
    P.obj("buffer~ ---hum_a 3000", 1100, 40, 200)
    P.obj("buffer~ ---hum_b 3000", 1100, 70, 200)
    i_msg = P.raw({"maxclass": "inlet", "numinlets": 0, "numoutlets": 1, "outlettype": [""], "patching_rect": [400, 40, 30, 30], "comment": "messages"})
    rt = P.obj("route set level tempo sr playing gate hum humbuf", 400, 80, 340)
    P.connect(i_msg, 0, rt, 0)
    ph = P.obj("phasor~ 1n @lock 1", 20, 80, 150)
    s16 = P.obj("*~ 16.", 20, 120)
    P.connect(ph, 0, s16, 0)
    step = P.obj("trunc~", 20, 150)
    P.connect(s16, 0, step, 0)
    frac = P.obj("-~", 120, 150, 40)
    P.connect(s16, 0, frac, 0); P.connect(step, 0, frac, 1)
    ch = P.obj("change~", 20, 180)
    P.connect(step, 0, ch, 0)
    bnd = P.obj("abs~", 20, 210)
    P.connect(ch, 0, bnd, 0)
    pat = P.obj("index~ ---kpat", 200, 180, 120)
    P.connect(step, 0, pat, 0)
    on = P.obj(">~ 0.", 200, 210)
    P.connect(pat, 0, on, 0)
    trg = P.obj("*~", 20, 240, 40)
    P.connect(bnd, 0, trg, 0); P.connect(on, 0, trg, 1)
    hs = P.obj("sah~ 0.5", 20, 270)
    P.connect(step, 0, hs, 0); P.connect(trg, 0, hs, 1)
    ha = P.obj("sah~ 0.5", 200, 270)
    P.connect(pat, 0, ha, 0); P.connect(trg, 0, ha, 1)
    # gap (in 16ths) from this hit to the next one, written by the engine (kick variations);
    # 0 = unknown → a whole bar
    gp = P.obj("index~ ---kgap", 330, 180, 120)
    P.connect(step, 0, gp, 0)
    hg = P.obj("sah~ 0.5", 330, 270)
    P.connect(gp, 0, hg, 0); P.connect(trg, 0, hg, 1)
    hz0 = P.obj("==~ 0.", 460, 270)
    P.connect(hg, 0, hz0, 0)
    hz1 = P.obj("*~ 16.", 460, 300)
    P.connect(hz0, 0, hz1, 0)
