CW, CH = 1240, 169         # the whole UI lives in Live's device strip (169 px high)


def build_main():
    P = Patcher((40, 40, 1500, 1000))
    P.comment("KØRE — main device patch (source). GENERATED by tools/build_patches.py. Status: STATIC VALID only.", 20, 8, 900)
    dev = P.obj("live.thisdevice", 20, 40)
    lb = P.obj("loadbang", 160, 40)
    start = P.msg("1", 20, 80)
    P.connect(dev, 0, start, 0); P.connect(lb, 0, start, 0)
    qm = P.obj("qmetro 10", 20, 120)
    P.connect(start, 0, qm, 0)
    tr = P.obj("transport", 20, 160, 160)
    P.connect(qm, 0, tr, 0)
    pk = P.obj("pack 0 0 0. 0 0.", 20, 200, 160)
    for i in range(5):
        P.connect(tr, i, pk, i)
    tick = P.obj("prepend tick", 20, 240)
    P.connect(pk, 0, tick, 0)
    eng = P.obj("js kore_engine.js", 20, 300, 200, varname="engine")
    P.connect(tick, 0, eng, 0)
    P.connect(dev, 0, eng, 0)
    path = P.msg("path live_set", 420, 40)
    P.connect(dev, 0, path, 0)
    lp = P.obj("live.path", 420, 80)
    P.connect(path, 0, lp, 0)
    for i, (prop, pre) in enumerate([("loop", "loopon"), ("loop_start", "loopstart"), ("loop_length", "looplength")]):
        x = 420 + i * 170
        pm = P.msg("property %s" % prop, x, 120)
        P.connect(dev, 0, pm, 0)
        ob = P.obj("live.observer", x, 160)
        P.connect(pm, 0, ob, 0); P.connect(lp, 0, ob, 1)
        pp = P.obj("prepend %s" % pre, x, 200)
        P.connect(ob, 0, pp, 0); P.connect(pp, 0, eng, 0)
    P.obj("pattr kore_state @bindto engine", 260, 300, 220, varname="kore_state", parameter_enable=1,
          saved_attribute_attributes={"valueof": {"parameter_longname": "kore_state", "parameter_shortname": "state",
                                                  "parameter_type": 3, "parameter_invisible": 1, "parameter_initial_enable": 0}})
    # events → high-priority pipe → voices
    rt = P.obj("route trig flush", 20, 360, 140)   # outlet 2 = everything else (kickbuf, kicklevel)
    P.connect(eng, 0, rt, 0)
    nv = 9  # track amp p0..p4 open pan
    up = P.obj("unpack 0" + " 0." * nv, 20, 400, 300)
    P.connect(rt, 0, up, 0)
    pipe = P.obj("pipe 0" + " 0." * (nv - 1) + " 0", 20, 440, 300)
    for i in range(nv + 1):
        P.connect(up, i, pipe, i)
    clr = P.msg("clear", 340, 400)
    P.connect(rt, 1, clr, 0); P.connect(clr, 0, pipe, 0)
    pk2 = P.obj("pack 0" + " 0." * (nv - 1), 20, 480, 300)
    for i in range(nv):
        P.connect(pipe, i, pk2, i)
    rv = P.obj("route 0 1 2 3 4 5", 20, 520, 200)
    P.connect(pk2, 0, rv, 0)
    voices = {}
    specs = [(1, "sub", 3), (3, "toml", 4), (4, "tomh", 4), (5, "hat", 1)]   # PUNCH: signal-domain player below
    for k, (idx, nm, n) in enumerate(specs):
        x = 240 + k * 210
        pn = P.obj("prepend note", x, 600)
        P.connect(rv, idx, pn, 0)
        poly = P.obj("poly~ kore_voice_%s %d @steal 1" % (nm, n), x, 640, 200)
        if nm != "sub":   # stereo (pan) voices
            pb = [b for b in P.boxes if b["box"]["id"] == poly][0]["box"]
            pb.update({"numoutlets": 2, "outlettype": ["signal", "signal"]})
        P.connect(pn, 0, poly, 0)
        voices[nm] = poly
    P.comment("HAT = 1 instance + steal: a new hat retriggers the same envelope → closed chokes open", 1080, 680, 300)
    # KICK: sample-accurate player (kore_kick) fed by the engine's buffers
    kick = P.obj("kore_kick", 20, 640, 120)
    kb = [b for b in P.boxes if b["box"]["id"] == kick][0]["box"]
    kb.update({"numinlets": 1, "numoutlets": 3, "outlettype": ["signal", "signal", "signal"]})
    kr = P.obj("route kickbuf kicklevel kickgate hum humbuf", 340, 400, 300)
    P.connect(rt, 2, kr, 0)
    for j_, pre_ in enumerate(["set", "level", "gate", "hum", "humbuf"]):
        b_ = P.obj("prepend %s" % pre_, 340 + j_ * 110, 440)
        P.connect(kr, j_, b_, 0); P.connect(b_, 0, kick, 0)
    ktempo = P.obj("prepend tempo", 200, 240)
    P.connect(tr, 4, ktempo, 0); P.connect(ktempo, 0, kick, 0)
    dsp = P.obj("dspstate~", 200, 560)
    P.connect(lb, 0, dsp, 0)
    ksr = P.obj("prepend sr", 200, 590)
    P.connect(dsp, 1, ksr, 0); P.connect(ksr, 0, kick, 0); P.connect(ksr, 0, eng, 0)
    bn = P.msg("bufnames ---kick_a ---kick_b ---kpat ---hum_a ---hum_b ---kgap", 600, 40)
    P.connect(dev, 0, bn, 0); P.connect(lb, 0, bn, 0); P.connect(bn, 0, eng, 0)
    # RUMBLE bus fed by the kick
    rum = P.obj("kore_rumble", 1100, 600, 120)
    rum_box = [b for b in P.boxes if b["box"]["id"] == rum][0]["box"]
    rum_box.update({"numinlets": 3, "numoutlets": 1, "outlettype": ["signal"]})
    P.connect(kick, 0, rum, 0)
    P.connect(rv, 2, rum, 1)
    P.connect(kick, 1, rum, 2)
    # low-end coordinator: SUB duck from the kick proximity (sample-accurate)
    le = MAP["lowEnd"]
    sd1 = P.obj("*~ %s" % f(le["subDuckDepth"]), 240, 700)
    P.connect(kick, 1, sd1, 0)
    sd2 = P.obj("!-~ 1.", 240, 730)
    P.connect(sd1, 0, sd2, 0)
    subd = P.obj("*~", 240, 760, 40)
    P.connect(voices["sub"], 0, subd, 0); P.connect(sd2, 0, subd, 1)
    def sumsig(srcs, x, y):
        acc = srcs[0]
        for j, s_ in enumerate(srcs[1:]):
            a_ = P.obj("+~", x + j * 60, y, 40)
            P.connect(acc[0], acc[1], a_, 0); P.connect(s_[0], s_[1], a_, 1)
            acc = (a_, 0)
        return acc
    # low end mono (kick, HUM, SUB, RUMBLE) → both sides; TOMs / HAT panned per hit
    mono = sumsig([(kick, 0), (kick, 2), (subd, 0), (rum, 0)], 20, 800)
    po = P.obj("plugout~", 20, 1030)
    pa = P.obj("peakamp~ 33", 400, 1000)
    mx = P.obj("maximum~", 400, 970)
    P.connect(mx, 0, pa, 0)
    pm1 = P.obj("prepend meter", 400, 1030)
    P.connect(pa, 0, pm1, 0); P.connect(pm1, 0, eng, 0)
    for ch in (0, 1):
        x0 = 20 + ch * 200
        side = sumsig([mono, (voices["toml"], ch), (voices["tomh"], ch), (voices["hat"], ch)], x0, 840 + ch * 20)
        dc = P.obj("svf~ %s 0.05" % f(le["dcBlockHz"]), x0, 900)
        P.connect(side[0], side[1], dc, 0)
        md = P.obj("*~ %s" % f(MAP["master"]["drive"]), x0, 930)
        th = P.obj("tanh~", x0, 960)
        ce = P.obj("*~ %s" % f(MAP["master"]["ceiling"]), x0, 990)
        P.connect(dc, 1, md, 0)
        P.chain(md, th, ce)
        P.connect(ce, 0, po, ch)
        ab = P.obj("abs~", x0 + 100, 1020)
        P.connect(ce, 0, ab, 0); P.connect(ab, 0, mx, ch)   # meter: the louder side
    pk_ = P.obj("peakamp~ 33", 360, 960)
    P.connect(kick, 0, pk_, 0)
    pm2 = P.obj("prepend kickmeter", 360, 990)
    P.connect(pk_, 0, pm2, 0); P.connect(pm2, 0, eng, 0)
    st = P.obj("route sync pending error", 260, 360, 180)
    P.connect(eng, 2, st, 0)
    syu = P.obj("unpack 0 0.", 600, 400, 80)
    P.connect(st, 0, syu, 0)
    kpl = P.obj("prepend playing", 600, 430)
    P.connect(syu, 0, kpl, 0); P.connect(kpl, 0, kick, 0)
    pr = P.obj("print KØRE", 420, 400)
    P.connect(st, 2, pr, 0)
    # UI: ONE jsui in the device strip (no separate editor window) — SEQ / SOUND / LANES tabs inside
    dl = P.obj("deferlow", 1100, 300)
    P.connect(eng, 1, dl, 0)
    ui = P.raw({"maxclass": "jsui", "filename": "kore_ui.js", "numinlets": 1, "numoutlets": 1,
                "outlettype": [""], "parameter_enable": 0, "border": 0, "patching_rect": [1100, 330, CW, CH],
                "presentation": 1, "presentation_rect": [0, 0, CW, CH], "varname": "kore_ui"})
    P.connect(dl, 0, ui, 0)
    P.connect(ui, 0, eng, 0)
    return P.dump(os.path.join(OUT, "kore_main.maxpat"), openinpresentation=1, devicewidth=float(CW))


