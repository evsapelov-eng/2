#!/usr/bin/env node
// Concatenates the ES5 core + Max adapter into max/kore_engine.js and copies the
// jsui file into max/. One self-contained file per Max object: no require(),
// no search-path surprises after Freeze.
"use strict";
const fs = require("fs");
const path = require("path");
const { sourceFiles } = require("./node_loader");

const ROOT = path.join(__dirname, "..");
const OUT = path.join(ROOT, "max");

function es5Check(file, text) {
  const banned = [/\blet\s/, /\bconst\s/, /=>/, /\bclass\s/, /`/, /Math\.imul/, /\.\.\.[a-zA-Z_]/, /Math\.random/,
    /Math\.(tanh|log10|log2|sign|hypot|trunc|cbrt|fround|expm1|log1p)\b/, /Array\.from/, /\.includes\(/, /padStart/,
    /Object\.assign/, /Number\.isFinite/, /\.findIndex\(/];
  const bad = banned.filter((re) => re.test(text.replace(/\/\/.*$/gm, "")));
  if (bad.length) throw new Error(`${file}: non-ES5/forbidden construct ${bad.join(", ")}`);
}

const parts = [];
for (const f of sourceFiles().concat([path.join(__dirname, "max_adapter.js")])) {
  const t = fs.readFileSync(f, "utf8");
  es5Check(path.basename(f), t);
  parts.push(`// ---- ${path.relative(ROOT, f)} ----\n${t}`);
}
// Legacy Max JS may read files with a non-UTF-8 codepage: escape everything non-ASCII.
const ascii = (t) => t.replace(/[^\x00-\x7f]/g, (c) => "\\u" + c.charCodeAt(0).toString(16).padStart(4, "0"));
const header = "// GENERATED by js/build.js — do not edit. Sources: kore/js/src + kore/js/max_adapter.js\n";
fs.writeFileSync(path.join(OUT, "kore_engine.js"), ascii(header + parts.join("\n")));

const uiSrc = path.join(__dirname, "ui", "kore_ui.js");
if (fs.existsSync(uiSrc)) {
  const map = JSON.parse(fs.readFileSync(path.join(ROOT, "spec", "dsp_map.json"), "utf8"));
  const strip = (o) => JSON.parse(JSON.stringify(o, (k, v) => (k === "_doc" ? undefined : v)));
  const t = "// injected from spec/dsp_map.json (units + preview model)\nvar KORE_DSP_MAP = " + JSON.stringify(strip(map)) + ";\n\n" +
    "// ---- js/shared/kore_dsp_model.js ----\n" + fs.readFileSync(path.join(__dirname, "shared", "kore_dsp_model.js"), "utf8") + "\n" +
    fs.readFileSync(uiSrc, "utf8");
  es5Check("kore_ui.js", t);
  fs.writeFileSync(path.join(OUT, "kore_ui.js"), ascii(header + t));
}
console.log("built max/kore_engine.js" + (fs.existsSync(uiSrc) ? " and max/kore_ui.js" : ""));
